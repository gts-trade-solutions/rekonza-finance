/** A printed label in the second language, or null when there is none (or no second language). */
export function translate(label: string, lang: PrintLanguage | null | undefined): string | null {
  if (!lang) return null;
  const i = (KEYS as readonly string[]).indexOf(label);
  return i < 0 ? null : T[lang][i] ?? null;
}

